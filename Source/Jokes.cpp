juce::String utf8 (const char* text) { return juce::String::fromUTF8 (text); }

template <size_t N>
juce::String pick (juce::Random& rng, const char* const (&items)[N])
{
    return utf8 (items[rng.nextInt ((int) N)]);
}

// Берём count случайных элементов без повторов, сохраняя исходный порядок.
template <size_t N>
juce::StringArray pickOrdered (juce::Random& rng, const char* const (&items)[N], int count)
{
    juce::Array<int> indices;
    for (int i = 0; i < (int) N; ++i)
        indices.add (i);

    while (indices.size() > count)
        indices.remove (rng.nextInt (indices.size()));

    juce::StringArray result;
    for (auto index : indices)
        result.add (utf8 (items[index]));
    return result;
}

