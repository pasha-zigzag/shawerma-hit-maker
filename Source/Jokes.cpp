juce::StringArray cookingStages (juce::Random& rng, int count)
{
    auto stages = pickOrdered (rng, kStagesStart, juce::jmax (1, count - 1));
    stages.add (pick (rng, kStagesFinal));
    return stages;
}

std::vector<Notification> successNotifications (juce::Random& rng, int count)
{
    constexpr int total = (int) (sizeof (kNotifications) / sizeof (kNotifications[0]));

    // Sonic Music и Ninja Records — классика, они всегда первые.
    std::vector<Notification> result { { utf8 (kNotifications[0][0]), utf8 (kNotifications[0][1]) },
                                       { utf8 (kNotifications[1][0]), utf8 (kNotifications[1][1]) } };

    juce::Array<int> rest;
    for (int i = 2; i < total; ++i)
        rest.add (i);

    while ((int) result.size() < count && ! rest.isEmpty())
    {
        const int index = rest.removeAndReturn (rng.nextInt (rest.size()));
        result.push_back ({ utf8 (kNotifications[index][0]), utf8 (kNotifications[index][1]) });
    }

    return result;
}

